'''
if → SE
elif → ALTRIMENTI SE
else → ALTRIMENTI

==================

if condizone:
    risultato
if condizone:
    risultato
else:
    risultato

==================
if + else = elif

if condizone:
    risultato
elif condizone:
    risultato
elif condizone:
    risultato
else:
    risultato
'''

numero = 25

if numero == 250:
    print("numero è 25")
elif numero > 200:
    print("numero maggiore di 20")
elif numero < 2:
    print("numero minore di 30")
else:
    print("fine")
