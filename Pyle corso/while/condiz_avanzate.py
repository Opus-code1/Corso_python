'''
OPERATORI DI CONFRONTO

AND =  e | anche ...
OR = oppure
NOT = non è
IN = dentro
'''
nome = "Sarah"
anni = 15
# con and tutte le condizioni devono essere vere
if nome == "Sarah" and anni == 15:
    print("waw ci sta")
else:
    print("nah")
    
# con or ALMENO una delle codizioni deve essere vera (una o più)
if nome == "Sarah" or anni == 15:
    print("ma sii daje")
else:
    print("nope")
    
# con il not si indica ciò che non è
if nome is not "Sarah":
    print("ma tu non sei Sarah")
else:
    print("ah sei Sarah")
    
# con in controllo se ho qualcosa dentro qualcosa
if 'S' in nome:
    print("il nome contiene una S")
else:
    print("il nome non contiene una S")
